def make_music():
    os.makedirs(os.path.join(ROOT, "music"), exist_ok=True)
    menu = track(100, [AM, F, C, G, AM, F, C, G], MENU_MELODY, "pulse", {"hat": 4}, 0.10, 1)
    match = track(150, [AM, F, C, G, AM, F, G, E] * 2, MATCH_MELODY, "octave",
                  {"kick": "two", "snare": True, "hat": 2}, 0.12, 2)
    write_ogg(os.path.join(ROOT, "music", "menu.ogg"), menu)
    write_ogg(os.path.join(ROOT, "music", "match.ogg"), match)


# ------------------------------------------------------------------ sound effects

def sweep(f0, f1, length, wave_fn="square", curve=1.0, duty=0.5):
    n = int(length * SR)
    t = np.arange(n) / SR
    k = (t / length) ** curve
    f = f0 * (f1 / f0) ** k
    ph = np.cumsum(f) / SR
    if wave_fn == "square":
        return np.where(ph % 1.0 < duty, 1.0, -1.0)
    if wave_fn == "tri":
        return 4.0 * np.abs(ph % 1.0 - 0.5) - 1.0
    return np.sin(2 * np.pi * ph)


def make_fx():
    os.makedirs(os.path.join(ROOT, "fx"), exist_ok=True)
    rng = np.random.default_rng(7)
    fx = {}
    # 乾坤挪移: a zip up and a pop on the other side
    a = sweep(300, 2400, 0.12, "square", duty=0.25) * env(int(0.12 * SR), r=0.02)
    b = sweep(1800, 900, 0.1, "square") * env(int(0.1 * SR), d=0.05, s=0.3, r=0.03)
    fx["blink"] = np.concatenate([a, np.zeros(int(0.03 * SR)), b])
    # 斗转星移: a wobble down that turns round and climbs back
    n = int(0.45 * SR)
    t = np.arange(n) / SR
    f = 700 - 450 * np.sin(np.pi * t / 0.45) + 60 * np.sin(2 * np.pi * 18 * t)
    fx["flip"] = np.where((np.cumsum(f) / SR) % 1.0 < 0.5, 1.0, -1.0) * env(n, d=0.2, s=0.6, r=0.06)
    # 重力转移: a heavy fall and a thud
    fall = sweep(900, 80, 0.4, "tri", curve=0.6) * env(int(0.4 * SR), r=0.02)
    thud = kick(0.25) * 1.2
    fx["gravity"] = np.concatenate([fall, thud])
    # 视角转移: a glitchy, bit-crushed stutter
    parts = []
    for i in range(7):
        m = int(0.035 * SR)
        f = rng.choice([220, 330, 440, 660, 990])
        tt = np.arange(m) / SR
        parts.append(np.where((f * tt) % 1.0 < 0.5, 1.0, -1.0) * (0.6 if i % 2 else 1.0))
        parts.append(noise(int(0.012 * SR), rng, 6) * 0.5)
    fx["view"] = np.concatenate(parts) * env(sum(len(p) for p in parts), r=0.05)
    # any other skill: a quick bright arpeggio
    fx["cast"] = np.concatenate([note(lambda f, t: square(f, t, 0.25), n, 0.05, r=0.01) for n in (72, 76, 79, 84)])
    # 规则转移 SHIFT!: a rising whoosh into a chord stab
    rise = (noise(int(0.35 * SR), rng, 3) * 0.35 + sweep(200, 1600, 0.35, "square", duty=0.25) * 0.4) * np.linspace(0.1, 1.0, int(0.35 * SR))
    stab = sum(note(square, n, 0.4, d=0.25, s=0.3, r=0.08) for n in (57, 64, 69, 72)) / 3.0
    fx["shift"] = np.concatenate([rise, stab + kick(0.4) * 0.6])
    # menu click, and the end-of-match jingles
    fx["click"] = note(lambda f, t: square(f, t, 0.25), 84, 0.035, r=0.01) * 0.6
    fx["win"] = np.concatenate([note(square, n, 0.11, r=0.02) for n in (72, 76, 79)] + [note(square, 84, 0.45, d=0.3, s=0.5, r=0.1)])
    fx["lose"] = np.concatenate([note(triangle, n, 0.16, r=0.03) for n in (67, 63, 60)] + [note(triangle, 55, 0.5, d=0.3, s=0.4, r=0.15)])
    for k, x in fx.items():
        x = x / (np.max(np.abs(x)) + 1e-9) * 0.8
        write_wav(os.path.join(ROOT, "fx", k + ".wav"), x)


if __name__ == "__main__":
    make_music()
    make_fx()
    print("ok")
