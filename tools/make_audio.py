"""Makes SHIFT PONG's music and skill sounds from scratch: a little chiptune
synth (square, triangle, noise), two looping tracks and the SHIFT sound
effects. Everything is original, generated by this script.

usage: python3 tools/make_audio.py   (writes sounds/music/*.ogg, sounds/fx/*.wav)
"""
import os, subprocess, wave
import numpy as np

SR = 32000
ROOT = os.path.join(os.path.dirname(__file__), "..", "sounds")


def midi_hz(n):
    return 440.0 * 2.0 ** ((n - 69) / 12.0)


def square(f, t, duty=0.5):
    return np.where((f * t) % 1.0 < duty, 1.0, -1.0)


def triangle(f, t):
    return 4.0 * np.abs((f * t) % 1.0 - 0.5) - 1.0


def noise(n, rng, step=1):
    v = rng.uniform(-1.0, 1.0, n // step + 1)
    return np.repeat(v, step)[:n]


def env(n, a=0.005, d=0.0, s=1.0, r=0.03):
    """Attack / decay to sustain / release, in seconds, over n samples."""
    t = np.arange(n) / SR
    e = np.ones(n) * s
    if d > 0:
        e = np.where(t < a + d, 1.0 - (1.0 - s) * np.clip((t - a) / d, 0, 1), s)
    e = np.where(t < a, t / max(a, 1e-6), e)
    rel = n / SR - r
    e = np.where(t > rel, e * np.clip((n / SR - t) / max(r, 1e-6), 0, 1), e)
    return e


def note(wave_fn, n_midi, length, **kw):
    n = int(length * SR)
    t = np.arange(n) / SR
    return wave_fn(midi_hz(n_midi), t) * env(n, **kw)


def place(buf, sig, at):
    i = int(at * SR)
    j = min(len(buf), i + len(sig))
    if j > i:
        buf[i:j] += sig[: j - i]


def kick(length=0.18):
    n = int(length * SR)
    t = np.arange(n) / SR
    f = 50 + 120 * np.exp(-t * 30)
    ph = 2 * np.pi * np.cumsum(f) / SR
    return np.sin(ph) * np.exp(-t * 14)


def snare(rng, length=0.14):
    n = int(length * SR)
    t = np.arange(n) / SR
    return noise(n, rng, 2) * np.exp(-t * 22) * 0.8 + np.sin(2 * np.pi * 190 * t) * np.exp(-t * 30) * 0.3


def hat(rng, length=0.04):
    n = int(length * SR)
    t = np.arange(n) / SR
    return noise(n, rng, 1) * np.exp(-t * 90)


def track(bpm, chords, melody, bass_style, drums, arp_level, seed):
    """chords: a chord (root midi, [chord tones]) per bar; melody: [(midi or None, sixteenths)]."""
    rng = np.random.default_rng(seed)
    six = 60.0 / bpm / 4.0
    bars = len(chords)
    total = bars * 16 * six
    buf = np.zeros(int(total * SR) + SR)
    for b, (root, tones) in enumerate(chords):
        t0 = b * 16 * six
        # bass: triangle
        for k in range(8):
            n = root - 24 + (12 if bass_style == "octave" and k % 2 else 0)
            if bass_style == "pulse" and k % 2:
                continue
            place(buf, note(triangle, n, six * 2 * 0.9, r=0.02) * 0.55, t0 + k * six * 2)
        # arpeggio: thin square, sixteenths
        for k in range(16):
            n = tones[k % len(tones)] + (12 if (k // len(tones)) % 2 else 0)
            place(buf, note(lambda f, t: square(f, t, 0.125), n, six * 0.9, r=0.01, d=0.05, s=0.5) * arp_level, t0 + k * six)
        # drums
        for k in range(16):
            at = t0 + k * six
            if "kick" in drums and k in (0, 8) or ("kick" in drums and drums.get("kick") == "four" and k in (4, 12)):
                place(buf, kick() * 0.7, at)
            if "snare" in drums and k in (4, 12):
                place(buf, snare(rng) * 0.35, at)
            if "hat" in drums and k % drums["hat"] == 0:
                place(buf, hat(rng) * (0.18 if k % 4 == 0 else 0.1), at)
    # melody: square lead with a touch of vibrato
    at = 0.0
    for n, d in melody:
        length = d * six
        if n is not None:
            m = int(length * SR)
            t = np.arange(m) / SR
            f = midi_hz(n) * (1.0 + 0.004 * np.sin(2 * np.pi * 5.5 * t) * np.clip(t / 0.15, 0, 1))
            ph = np.cumsum(f) / SR
            sig = np.where(ph % 1.0 < 0.5, 1.0, -1.0) * env(m, d=0.12, s=0.7, r=0.03)
            place(buf, sig * 0.26, at)
        at += length
    buf = buf[: int(total * SR)]
    return buf / (np.max(np.abs(buf)) + 1e-9) * 0.85


def write_wav(path, x):
    x = np.clip(x, -1, 1)
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes((x * 32767).astype(np.int16).tobytes())


def write_ogg(path, x):
    tmp = path + ".tmp.wav"
    write_wav(tmp, x)
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", tmp, "-ac", "2", "-c:a", "vorbis", "-strict", "-2", "-q:a", "4", path], check=True)
    os.remove(tmp)


